// Shared clinical types used across Records, Nurse Station, Consultation, Wards.
// These mirror the routine clinical workflow: appointment → triage → vitals →
// consultation → treatment / admission / referral → discharge.

export type VisitStatus =
  | "booked"             // Records booked the appointment, patient not yet checked in.
  | "checked-in"         // Patient arrived at facility.
  | "awaiting-triage"    // Sitting in nurse queue.
  | "in-triage"          // Nurse is triaging.
  | "awaiting-vitals"    // Triaged, waiting for vitals to be taken.
  | "in-vitals"
  | "awaiting-consultation"
  | "in-consultation"
  | "awaiting-lab"
  | "awaiting-pharmacy"
  | "admitted"
  | "discharged"
  | "completed"
  | "cancelled";

export type TriagePriority = "emergency" | "urgent" | "semi" | "routine" | "pending";

export type VisitType = "opd" | "anc" | "lab" | "radiology" | "ward";

export type Visit = {
  id: string;                    // Internal visit id (V…)
  visitNo: string;               // Human-readable visit number (V251122001 style)
  patientId: string;
  patientName: string;
  patientSex: "M" | "F";
  patientDob: string;
  patientPhone: string;
  visitType: VisitType;
  serviceId: string;
  serviceName: string;
  department: string;
  clinicianId: string;
  clinicianName: string;
  fee: number;
  sponsor: string;               // e.g. "SELF PAY / UNINSURED - GH" or "NHIS"
  scheme: string;
  appointmentDate: string;       // YYYY-MM-DD
  appointmentTime: string;       // HH:mm
  reason: string;
  priority: TriagePriority;
  status: VisitStatus;
  /** Human label from backend {@code EncounterDto.currentStation} */
  currentStationLabel: string;
  source: "records" | "walk-in" | "internal-referral";
  createdAt: string;             // ISO timestamp
};


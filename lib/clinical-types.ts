// ── Billing ──────────────────────────────────────────────────────────────
// Each clinical event that has a price generates a billing line item. The
// item travels with the visit and is settled by the billing/cashier officer.

export type BillingItemKind =
  | "consultation"
  | "lab"
  | "radiology"
  | "pharmacy"
  | "procedure"
  | "ward"
  | "other";

export type BillingItemStatus = "pending" | "paid" | "claimed" | "waived" | "cancelled";

export type BillingLineItem = {
  id: string;
  visitId: string;
  patientId: string;
  kind: BillingItemKind;
  description: string;
  quantity: number;
  unitPrice: number;
  amount: number;
  sponsor: string;                  // SELF PAY, NHIS, …
  serviced: boolean;                // True once the service has been delivered
  servicedAt?: string;
  status: BillingItemStatus;
  paidAt?: string;
  paymentMethod?: string;
  receiptNo?: string;
  sourceRef?: string;               // FK back to lab order / prescription / etc.
  createdBy: string;
  createdAt: string;
};
